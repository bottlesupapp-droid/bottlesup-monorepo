BAR = "-- " + "=" * 100


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def code_of(sql: str) -> str:
    return re.sub(r"--[^\n]*", "", sql)


def created_functions(sql: str):
    return re.findall(r"create\s+function\s+public\.([a-z_0-9]+)\(", code_of(sql), re.I)


def created_tables(sql: str):
    return re.findall(r"create\s+table\s+public\.([a-z_0-9]+)", code_of(sql), re.I)


def added_columns(sql: str):
    """Every column an `alter table public.T add column ...[, add column ...];` statement adds."""
    out = []
    for m in re.finditer(r"alter\s+table\s+public\.([a-z_0-9]+)\s+(add\s+column[^;]*);", code_of(sql), re.I):
        for c in re.findall(r"add\s+column\s+([a-z_0-9]+)", m.group(2), re.I):
            out.append((m.group(1), c))
    return out


def build_apply() -> str:
    parts = [
        "-- ALL SEVEN BRIEF-3 MIGRATIONS IN ONE PASTE (website branch feat/business-brief-3, same bytes as apps/bottles-up-website-main/supabase/migrations/20261021100000 .. 20261027100000):\n"
        "-- floor plan and table states, the order stage Accepted, refund policy and requests, staff discounts and free bottles, payout settings and ledger, door sales and the shift summary, each venue's time zone.\n"
        "-- GENERATED by supabase/go-live/build_business_brief_3.py: do not edit it by hand (python3 -I supabase/go-live/build_business_brief_3.py --check says whether it is current).\n"
        "-- HOW: run supabase/audit/18_preflight_business_brief_3.sql FIRST (it must return no rows), then paste this whole file into the Supabase dashboard > SQL editor (production project)\n"
        "-- and Run. Each migration is wrapped in its own begin/commit, in this order, so an error rolls back THAT migration and stops the rest (the earlier ones stay applied; send the\n"
        "-- error text, do not edit a file). Then run supabase/audit/19_postflight_business_brief_3.sql: every row ok = true. THEN deploy the edge functions (see supabase/go-live/README.md 1h).\n"
        "-- Two of the migrations REPLACE live functions (floor plan: 3, Accepted: 4). Each replacement is guarded: it happens only if the live function is exactly the version the\n"
        "-- repository has; anything else STOPS that migration before anything is changed (and the preflight lists it first).\n"
        "-- UNDO: supabase/go-live/rollback_business_brief_3.sql. Never use `supabase db push`.\n\n"
    ]
    for name in NAMES:
        body = read(MIG / f"{name}.sql")
        parts.append(f"{BAR}\n-- {name}\n{BAR}\nbegin;\n{body}")
        if not body.endswith("\n"):
            parts.append("\n")
        parts.append("commit;\n\n")
    return "".join(parts).rstrip("\n") + "\n"


def split_functions(sql: str):
    """The `CREATE OR REPLACE FUNCTION` statements of a fixture file, each as text ending at its closing dollar quote."""
    chunks = re.split(r"(?m)^(?=CREATE OR REPLACE FUNCTION )", sql)
    out = {}
    for c in chunks:
        m = re.match(r"CREATE OR REPLACE FUNCTION public\.([a-z_0-9]+)\(", c)
        if m:
            out[m.group(1)] = c.strip().rstrip(";") + ";"
    return out


def function_names(sql_files):
    names = []
    for f in sql_files:
        names += created_functions(read(MIG / f"{f}.sql"))
    return names


def build_rollback() -> str:
    floor = read(MIG / f"{NAMES[0]}.sql")
    refund = read(MIG / f"{NAMES[2]}.sql")
    disc = read(MIG / f"{NAMES[3]}.sql")
    pay = read(MIG / f"{NAMES[4]}.sql")
    door = read(MIG / f"{NAMES[5]}.sql")
    before_floor = split_functions(read(FIX / "floor_before.sql"))
    before_acc = split_functions(read(FIX / "order_accepted_before.sql"))
    for need in ("get_unavailable_table_types", "desk_walkin_options", "desk_create_walkin"):
        assert need in before_floor, need
    for need in ("desk_set_service_status", "desk_tonight", "night_report_data", "update_bottle_service_status"):
        assert need in before_acc, need

    def arr(xs):
        return "array[" + ", ".join(f"'{x}'" for x in xs) + "]"

    def drop_functions(names, why):
        return (
            f"-- {why}\n"
            "do $d$\ndeclare r record;\nbegin\n"
            f"  for r in select p.oid::regprocedure as sig from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'public' and p.proname = any({arr(names)}) loop\n"
            "    execute 'drop function ' || r.sig;\n  end loop;\nend\n$d$;\n"
        )

    def restore(name, chunk, marker):
        assert "$restore$" not in chunk
        return (
            f"-- {name}: put the previous version back, but only if the live one is the version this change wrote (it mentions '{marker}').\n"
            "do $r$\nbegin\n"
            f"  if exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'public' and p.proname = '{name}' and position('{marker}' in p.prosrc) > 0) then\n"
            f"    execute $restore${chunk}$restore$;\n"
            f"  else\n    raise notice '{name}() is not the version this change wrote, so it was left alone';\n  end if;\nend\n$r$;\n"
        )

    # the trigger function as 20261021100000 wrote it (20261023100000 replaced it)
    m = re.search(r"create function public\.site_table_bookings_snapshot_terms\(\).*?\n\$\$;", floor, re.S | re.I)
    assert m
    snapshot_v1 = re.sub(r"(?i)^create function", "create or replace function", m.group(0))

    out = []
    out.append(
        "-- UNDO for the seven brief-3 website migrations 20261021100000 .. 20261027100000: floor plan and table states, the order stage Accepted, refund policy and requests, staff discounts\n"
        "-- and free bottles, payout settings and ledger, door sales and the shift summary, each venue's time zone. GENERATED by supabase/go-live/build_business_brief_3.py: do not edit it by hand. It runs in ONE transaction (all or nothing).\n"
        "--\n"
        "-- WHAT IT DOES: puts back the previous versions of the seven live functions the migrations replaced (only where the live one is the version they wrote; otherwise it leaves\n"
        "-- it and says so), puts the five-value service status constraint back, and drops everything the migrations created (functions, tables, columns, the trigger).\n"
        "-- WHAT IT DELETES (data): table holds and unavailable tables and the record of bookings moved; the venues' deposit terms and what each booking was sold under (deposit terms,\n"
        "-- included admissions, refund policy); refund policies and requests; discount limits and the record of discounts and free bottles; payout settings, overrides, accounts and items; and, for door sales, the columns that say how an order was sold (the orders themselves stay); and the time zones venues chose (they read as Toronto again).\n"
        "-- What stays: the bookings themselves, a table's lowered total after a discount (the discounted amount stays off; only the record of why is gone), a free bottle's line (a normal\n"
        "-- line at no charge), and everything already paid or refunded (the website's own refund record is not touched).\n"
        "-- IT REFUSES (and changes nothing) while: any bottle line is 'accepted' (move them on first: Preparing or later), a refund is approved, being returned or paid back, or a payout\n"
        "-- is being sent or paid, or any ticket was sold at the door (cash and terminal totals). Those are records of money; keep them, and send me the message.\n"
        "-- AFTER IT: redeploy the previous edge functions (README 1h, \"going back\"): the new ones call functions this removes. Then supabase/audit/18_preflight_business_brief_3.sql returns\n"
        "-- no rows once everything is gone (the post-flight 19 then fails, as it should).\n"
        "begin;\n\n"
    )
    out.append(
        "do $refuse$\nbegin\n"
        "  if exists (select 1 from public.site_table_booking_bottles where service_status = 'accepted') then\n"
        "    raise exception 'some bottle orders are in the stage Accepted: move them to Preparing (or later) first. Nothing was changed.';\n  end if;\n"
        "  if to_regclass('public.site_refund_requests') is not null and exists (select 1 from public.site_refund_requests where status in ('approved', 'processing', 'completed')) then\n"
        "    raise exception 'refunds have been approved or paid back: that is a record of money, so it is kept. Nothing was changed.';\n  end if;\n"
        "  if to_regclass('public.site_payout_items') is not null and exists (select 1 from public.site_payout_items where status in ('processing', 'paid')) then\n"
        "    raise exception 'payouts have been sent or paid: that is a record of money, so it is kept. Nothing was changed.';\n  end if;\n"
        "  if exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'site_orders' and column_name = 'sale_channel') and exists (select 1 from public.site_orders where sale_channel = 'door') then\n"
        "    raise exception 'tickets have been sold at the door: the cash and terminal totals are a record of money, so they are kept. Nothing was changed.';\n  end if;\n"
        "end\n$refuse$;\n\n"
    )

    out.append("-- ---------------------------------------------------------------------------------------------------\n-- 7. each venue's time zone\n-- ---------------------------------------------------------------------------------------------------\n")
    out.append(drop_functions(["save_venue_time_zone"], "the time zone function (venue_timezone itself is dropped with the refund functions below, which created it)"))
    out.append("alter table public.site_venues drop column if exists time_zone;\n\n")

    out.append("-- ---------------------------------------------------------------------------------------------------\n-- 6. door sales and the shift summary\n-- ---------------------------------------------------------------------------------------------------\n")
    out.append(drop_functions(created_functions(door), "the door sales functions"))
    out.append("drop index if exists public.site_orders_door_sale_key;\n")
    out.append("alter table public.site_orders drop constraint if exists site_orders_door_sale_check;\n")
    out.append("alter table public.site_orders drop column if exists sale_channel, drop column if exists door_payment_method, drop column if exists door_reference, drop column if exists sold_by, drop column if exists door_client_key;\n\n")

    out.append("-- ---------------------------------------------------------------------------------------------------\n-- 5. payouts\n-- ---------------------------------------------------------------------------------------------------\n")
    out.append(drop_functions(created_functions(pay), "the payout functions"))
    out.append("drop table if exists public.site_payout_item_bookings, public.site_payout_items, public.site_payout_accounts, public.site_payout_overrides, public.site_payout_settings;\n\n")

    out.append("-- ---------------------------------------------------------------------------------------------------\n-- 4. discounts and free bottles\n-- ---------------------------------------------------------------------------------------------------\n")
    out.append(drop_functions(created_functions(disc), "the discount functions"))
    out.append("drop table if exists public.site_concessions, public.site_discount_limits;\n")
    out.append("alter table public.site_table_bookings drop column if exists staff_discount_cents;\n\n")

    out.append("-- ---------------------------------------------------------------------------------------------------\n-- 3. refund policy and requests\n-- ---------------------------------------------------------------------------------------------------\n")
    refund_fns = created_functions(refund)
    out.append(drop_functions(refund_fns, "the refund functions"))
    out.append("drop table if exists public.site_refund_requests, public.site_refund_policies;\n")
    out.append("alter table public.site_table_bookings drop column if exists refund_policy;\n")
    out.append("-- the trigger function goes back to the version 20261021100000 wrote (the refund migration added the policy copy to it)\n")
    out.append(snapshot_v1 + "\n\n")

    out.append("-- ---------------------------------------------------------------------------------------------------\n-- 2. the order stage Accepted\n-- ---------------------------------------------------------------------------------------------------\n")
    out.append(
        "alter table public.site_table_booking_bottles drop constraint if exists site_table_booking_bottles_service_status_check;\n"
        "alter table public.site_table_booking_bottles add constraint site_table_booking_bottles_service_status_check\n"
        "  check (service_status = any (array['awaiting_prep', 'preparing', 'ready', 'picked_up', 'served']));\n"
    )
    for name in ("desk_set_service_status", "desk_tonight", "night_report_data", "update_bottle_service_status"):
        out.append(restore(name, before_acc[name], "accepted"))
    out.append("\n")

    out.append("-- ---------------------------------------------------------------------------------------------------\n-- 1. floor plan and table states\n-- ---------------------------------------------------------------------------------------------------\n")
    for name in ("get_unavailable_table_types", "desk_walkin_options", "desk_create_walkin"):
        out.append(restore(name, before_floor[name], "site_table_taken_count"))
    out.append("drop trigger if exists site_table_bookings_snapshot_terms on public.site_table_bookings;\n")
    floor_fns = [f for f in created_functions(floor)]
    out.append(drop_functions(floor_fns, "the floor plan functions (the shared count last: the restored functions above no longer call it)"))
    out.append("drop table if exists public.site_booking_moves, public.site_table_blocks;\n")
    out.append("alter table public.site_table_bookings drop column if exists included_admissions, drop column if exists deposit_terms;\n")
    out.append("alter table public.site_table_types drop column if exists included_admissions;\n")
    out.append("alter table public.site_venues drop column if exists deposit_terms;\n\n")
    out.append("commit;\n")
    return "".join(out)


