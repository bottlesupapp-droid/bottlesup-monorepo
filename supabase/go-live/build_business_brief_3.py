def sql_array(xs):
    return "array[" + ",".join(f"'{x}'" for x in xs) + "]::text[]"


def all_new():
    fns, tables, cols = [], [], []
    for n in NAMES:
        sql = read(MIG / f"{n}.sql")
        fns += created_functions(sql)
        tables += created_tables(sql)
        cols += [f"{t}.{c}" for t, c in added_columns(sql)]
    return fns, tables, cols


def build_preflight() -> str:
    fns, tables, cols = all_new()
    rows = []
    rows.append(f"""select 'function already exists' as problem, p.proname::text as name
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
 where n.nspname = 'public' and p.proname = any({sql_array(fns)})""")
    rows.append(f"""select 'table already exists', t from unnest({sql_array(tables)}) t where to_regclass('public.' || t) is not null""")
    rows.append(f"""select 'column already exists', x from unnest({sql_array(cols)}) x
  where exists (select 1 from information_schema.columns c where c.table_schema = 'public' and c.table_name = split_part(x, '.', 1) and c.column_name = split_part(x, '.', 2))""")
    rows.append("""select 'trigger already exists', t.tgname::text from pg_trigger t where t.tgname = 'site_table_bookings_snapshot_terms' and not t.tgisinternal""")
    rows.append("""select 'constraint already exists', c.conname::text from pg_constraint c where c.conname = 'site_orders_door_sale_check' and c.conrelid = to_regclass('public.site_orders')""")
    rows.append("""select 'index already exists', 'site_orders_door_sale_key' where to_regclass('public.site_orders_door_sale_key') is not null""")
    rows.append(f"""select 'MISSING prerequisite function', f from unnest({sql_array(PREREQ_FUNCTIONS)}) f
  where not exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'public' and p.proname = f)""")
    rows.append(f"""select 'MISSING prerequisite table', t from unnest({sql_array(PREREQ_TABLES)}) t where to_regclass('public.' || t) is null""")
    rows.append(f"""select 'MISSING prerequisite column', x from unnest({sql_array(PREREQ_COLUMNS)}) x
  where not exists (select 1 from information_schema.columns c where c.table_schema = 'public' and c.table_name = split_part(x, '.', 1) and c.column_name = split_part(x, '.', 2))""")
    values = ",\n         ".join(f"('{n}', '{a}', '{f}', '{m}')" for n, a, f, m in REPLACED)
    rows.append(f"""select 'live function is neither the expected version nor the new one (that migration will STOP; reconcile by hand first)',
       x.fname || ' = ' || md5(btrim(regexp_replace(p.prosrc, '\\s+', ' ', 'g')) || '|' || p.prosecdef::text || '|' || coalesce(p.proconfig::text, ''))
  from (values
         {values}
       ) as x(fname, fargs, expected, marker)
  join pg_proc p on p.proname = x.fname and pg_get_function_identity_arguments(p.oid) = x.fargs
  join pg_namespace n on n.oid = p.pronamespace and n.nspname = 'public'
 where position(x.marker in p.prosrc) = 0
   and md5(btrim(regexp_replace(p.prosrc, '\\s+', ' ', 'g')) || '|' || p.prosecdef::text || '|' || coalesce(p.proconfig::text, '')) <> x.expected""")
    rows.append(f"""select 'live function does not exist with the expected arguments', x.fname
  from (values {", ".join(f"('{n}', '{a}')" for n, a, f, m in REPLACED)}) as x(fname, fargs)
 where not exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'public' and p.proname = x.fname and pg_get_function_identity_arguments(p.oid) = x.fargs)""")
